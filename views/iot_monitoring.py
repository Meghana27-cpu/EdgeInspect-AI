import pandas as pd
import plotly.graph_objects as go
import streamlit as st
import config
from modules import database as db, services, ui
from modules.mqtt_handler import SENSORS


def render():
    s, hub = services.settings(), services.hub()
    ui.header("IoT Monitoring", "Simulated conveyor sensors with optional MQTT transport and alerting", ui.pill("SIMULATED SENSORS", "orange"))
    a, b, c, d = st.columns([1, 1, 1, 3])
    if a.button("Start", type="primary", disabled=hub.running):
        hub.start(); st.rerun()
    if b.button("Stop", disabled=not hub.running):
        hub.stop(); st.rerun()
    fault = c.selectbox("Inject fault", ["-"] + list(SENSORS), label_visibility="collapsed")
    if fault != "-" and d.button(f"Trigger {fault} fault (12 s)"):
        hub.inject_fault(fault)
    if hub.mqtt_error:
        ui.note(hub.mqtt_error + ". The hub runs in local simulation mode; install/start a broker (e.g. Mosquitto) to use MQTT.", warn=True)
    src = st.selectbox("Alert source filter", ["All", "inspection", "iot"])

    @st.fragment(run_every=2 if hub.running else None)
    def panel():
        snap = hub.snapshot()
        v, bad = snap["values"], snap["abnormal"]
        tone = lambda k: "red" if k in bad else "green"
        st_tone = {"RUNNING": "green", "FAULT": "red"}.get(snap["status"], "gray")
        ui.kpi_row([("Conveyor speed", f"{v['belt_speed']:.2f} m/s", f"limits {s['belt_speed_min']}-{s['belt_speed_max']}", tone("belt_speed")),
                    ("Product temperature", f"{v['temperature']:.1f} °C", f"max {s['temp_max']}", tone("temperature")),
                    ("Vibration", f"{v['vibration']:.2f} mm/s", f"max {s['vibration_max']}", tone("vibration")),
                    ("Production count", f"{snap['production']:,}", "units (simulated)", "cyan"),
                    ("Machine status", snap["status"], snap["mode"], st_tone)])
        if not snap["running"]:
            ui.empty("Sensor hub stopped", "Press Start to begin the simulated stream.")
        else:
            cols = st.columns(3)
            lim = {"belt_speed": (s["belt_speed_min"], s["belt_speed_max"]), "temperature": (None, s["temp_max"]), "vibration": (None, s["vibration_max"])}
            for col, k in zip(cols, SENSORS):
                h = snap["hist"][k]
                if not h:
                    continue
                fig = go.Figure(go.Scatter(x=[pd.Timestamp(t, unit="s") for t, _ in h], y=[x for _, x in h], mode="lines", line=dict(color="#22D3EE", width=2)))
                for y in lim[k]:
                    if y is not None:
                        fig.add_hline(y=y, line_dash="dash", line_color="#EF4444")
                fig.update_layout(title=f"{k.replace('_', ' ').title()} ({SENSORS[k][0]})")
                ui.show_plot(ui.style_fig(fig, 260, False), f"iot_{k}", col)
        st.markdown("#### Alerts")
        al = db.list_alerts(50, src)
        if al.empty:
            ui.empty("No alerts yet", "Defect alerts from inspections and abnormal sensor readings appear here.")
        else:
            ui.show_df(al[["ts", "source", "level", "message", "product_id"]])
    panel()
    ui.note("Every sensor value on this page is generated by software and stored with simulated=1. Production count increments by simulation, not by the inspection results.")
